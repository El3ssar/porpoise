    @Test func r2UsesItsDocumentedDestinationConditions() async throws {
        let location = S3Location(
            bucket: "bucket", endpoint: URL(string: "https://fixture.r2.cloudflarestorage.com")!, region: "auto", accountID: location.accountID)
        let transport = CloudHTTPTransport(send: { request in
            let method = request.httpMethod!
            let status = method == "HEAD" ? 404 : 200
            if method == "PUT" {
                #expect(request.value(forHTTPHeaderField: "cf-copy-destination-if-none-match") == "*")
                #expect(request.value(forHTTPHeaderField: "x-amz-copy-source-if-match") == "source-etag")
                #expect(request.value(forHTTPHeaderField: "Authorization")?.contains("/auto/s3/aws4_request") == true)
            }
            let xml =
                method == "PUT"
                ? "<CopyObjectResult><ETag>copied-etag</ETag></CopyObjectResult>"
                : "<ListBucketResult><IsTruncated>false</IsTruncated></ListBucketResult>"
            return (Data(xml.utf8), HTTPURLResponse(url: request.url!, statusCode: status, httpVersion: nil, headerFields: nil)!)
        })
        let client = S3Client(location: location, directory: server.scratch.url, transport: transport)
        try await client.copy(S3Object(key: "source", size: 3, etag: "source-etag"), to: "target")
        let blocked = S3Client(
            location: location, directory: server.scratch.url,
            transport: CloudHTTPTransport(send: { _ in
                Issue.record("Unsupported R2 multipart copy must not make requests"); throw S3Error.invalidResponse
            }))
        do {
            try await blocked.copy(S3Object(key: "source", size: 6 * 1024 * 1024 * 1024, etag: "source-etag"), to: "target")
            Issue.record("Expected unsupported R2 source conditions")
        } catch RemoteError.unsupported(_) {}
        let scratch = try Scratch(), sparse = try scratch.file("large.bin", "")
        let handle = try FileHandle(forWritingTo: sparse)
        try handle.truncate(atOffset: 6 * 1024 * 1024 * 1024); try handle.close()
