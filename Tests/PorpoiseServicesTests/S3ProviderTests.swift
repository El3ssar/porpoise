    @Test func multipartResumeAfterAcknowledgedPartAndAbort() async throws {
        let local = try Scratch(), file = try local.file("large.bin", "")
        try Data(repeating: 42, count: 17 << 20).write(to: file)
        let operation = UUID()
        try await configure(["failPart": 2])
        do { try await client.upload(file, key: "large.bin", operationID: operation); Issue.record("Expected interrupted part") } catch {}
        #expect(try client.journal.load(operation)?.parts.count == 1)
        // New client models restart: durable journal skips acknowledged part 1.
        let restarted = S3Client(location: location, directory: server.scratch.url.appendingPathComponent("journal"))
        try await restarted.upload(file, key: "large.bin", operationID: operation)
        #expect(try await stats()["parts"] as? [Int] == [1, 2, 3])
        #expect(try await stats()["initiated"] as? Int == 1)
        #expect(try await restarted.head("large.bin").size == 17 << 20)
        #expect(try restarted.journal.load(operation) == nil)
        let aborted = UUID()
        try await configure(["failPart": 1])
        do { try await client.upload(file, key: "abort.bin", operationID: aborted) } catch {}
        try await client.abortUpload(operationID: aborted)
        #expect(try client.journal.load(aborted) == nil)
    }
